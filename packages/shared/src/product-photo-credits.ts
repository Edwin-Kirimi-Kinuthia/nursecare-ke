/** The credit for a product image URL such as "/products/zyrtec.jpg", or null for an uploaded photo. */
export function productPhotoCredit(imageUrl: string | null | undefined): PhotoCredit | null {
  const m = imageUrl?.match(/\/products\/([\w.-]+)$/);
  return m ? PRODUCT_PHOTO_CREDITS[m[1]!] ?? null : null;
}
