#!/usr/bin/env bash
# Look at the app in a browser, with no phone, emulator or store account.
#
#   npm run preview            # builds, then serves on http://<this-machine>:8099
#
# This renders the SAME screens through react-native-web, against the live API. It is
# a faithful look at layout, wording and flow, NOT the real native app: video calls,
# push notifications and secure storage don't exist in a browser, so for the preview
# the session is kept in memory (sign-in is lost on refresh) and push is switched off.
# To run the real thing on an Android phone, see "Test on a real phone" in README.md.
set -euo pipefail
cd "$(dirname "$0")/.."
PORT="${PORT:-8099}"
OUT="${TMPDIR:-/tmp}/carebora-web-preview"

cp app.json app.json.preview-bak
cleanup() {
  mv -f app.json.preview-bak app.json
  rm -f src/lib/tokens.web.ts src/lib/push.web.ts
}
trap cleanup EXIT

cat > src/lib/tokens.web.ts <<'TS'
// Preview only (generated by scripts/preview-web.sh, removed afterwards).
let a: string | null = null, r: string | null = null;
export type TokenPair = { accessToken: string; refreshToken: string };
export const loadTokens = async () => {};
export const getAccessToken = () => a;
export const getRefreshToken = () => r;
export const hasSession = () => r !== null;
export const saveTokens = async (p: TokenPair) => { a = p.accessToken; r = p.refreshToken; };
export const clearTokens = async () => { a = null; r = null; };
TS
cat > src/lib/push.web.ts <<'TS'
// Preview only (generated by scripts/preview-web.sh, removed afterwards).
export const routeForLink = (_l: unknown): string | null => null;
export const unregisterThisDevice = async () => {};
export type PushPermission = "undetermined" | "granted" | "denied";
export const usePushPermission = (_s: boolean) => ({ permission: "granted" as PushPermission, enable: async () => {} });
export const useNotificationTaps = (_s: boolean) => {};
TS
python3 - <<'PY'
import json
d = json.load(open("app.json"))
d["expo"]["platforms"] = ["ios", "android", "web"]
d["expo"]["web"] = {"output": "single", "bundler": "metro"}
json.dump(d, open("app.json", "w"), indent=2)
PY

rm -rf "$OUT"
npx expo export --platform web --output-dir "$OUT" >/dev/null
cleanup; trap - EXIT   # the source tree is back to normal before we start serving

IP="$(hostname -I 2>/dev/null | awk '{print $1}')"
echo
echo "Preview ready:"
echo "  this computer : http://localhost:$PORT"
[ -n "$IP" ] && echo "  your phone    : http://$IP:$PORT   (same Wi-Fi)"
echo "Press Ctrl+C to stop."
exec npx --yes serve -s "$OUT" -l "tcp://0.0.0.0:$PORT"
